export const GLYPH_H = 7;
const GLYPHS = new Map();
for (const [ch, def] of Object.entries(RAW)) {
  const rows = def.split('|');
  const w = rows[0].length;
  const px = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < w; x++) if (row[x] === '#') px.push(x, y);
  });
  GLYPHS.set(ch, { w, px });
}
const SPACE = { w: 3, px: [] };

function glyph(ch) {
  if (ch === ' ') return SPACE;
  return GLYPHS.get(ch) || GLYPHS.get(ch.toUpperCase()) || GLYPHS.get('?');
}

export function measureText(text, scale = 1) {
  let w = 0;
  for (let i = 0; i < text.length; i++) {
    w += glyph(text[i]).w;
    if (i < text.length - 1) w += 1;
  }
  return w * scale;
}

// Calls fn(x, y) for each lit font pixel (unscaled, origin top-left).
export function forEachPixel(text, fn) {
  let cx = 0;
  for (let i = 0; i < text.length; i++) {
    const g = glyph(text[i]);
    for (let j = 0; j < g.px.length; j += 2) fn(cx + g.px[j], g.px[j + 1]);
    cx += g.w + 1;
  }
}
